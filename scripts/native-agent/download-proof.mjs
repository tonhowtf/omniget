import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
const dir=path.resolve(process.argv[2]);
if(!dir.endsWith('/docs/native-agent-access/evidence/integration'))throw Error('Isolated proof output required');
const [id,digest,name]=process.argv.slice(3);
if(!/^[0-9a-f-]{36}$/.test(id)||!/^[a-f0-9]{64}$/.test(digest)||!/^client-(claude|codex)\.(png|mp4)$/.test(name))throw Error('Invalid artifact parameters');
const grant=JSON.parse(await readFile(path.join(dir,'credentials.json'),'utf8'));
const {base}=JSON.parse(await readFile(path.join(dir,'summary.json'),'utf8'));
const r=await fetch(`${base}/mcp/artifacts/${id}`,{headers:{Authorization:`Bearer ${grant.token}`,'If-Match':`"${digest}"`}});
if(!r.ok)throw Error(`HTTP ${r.status}`);const bytes=Buffer.from(await r.arrayBuffer());
if(createHash('sha256').update(bytes).digest('hex')!==digest)throw Error('Digest mismatch');
const file=path.join(dir,name);await writeFile(file,bytes);console.log(JSON.stringify({file,bytes:bytes.length,sha256:digest}));

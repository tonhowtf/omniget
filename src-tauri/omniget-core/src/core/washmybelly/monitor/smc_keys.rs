/// The chip family of a CPU brand string (`Apple M4 Pro`, `Intel(R) Core...`).
pub fn family(brand: &str) -> u16 {
    let b = brand.to_ascii_lowercase();
    if b.contains("intel") {
        return INTEL;
    }
    let pro = b.contains(" pro") || b.contains(" max") || b.contains(" ultra");
    if b.contains("a18") {
        A18
    } else if b.contains("m1") {
        M1
    } else if b.contains("m2") {
        M2
    } else if b.contains("m3") {
        M3
    } else if b.contains("m4") {
        if pro {
            M4_PRO
        } else {
            M4_BASE
        }
    } else if b.contains("m5") {
        M5
    } else if b.contains("apple") {
        // A newer Apple chip than the table knows: the generic Apple keys
        // still work, per-core keys do not.
        APPLE & !(M1 | M2 | M3 | M4 | M5 | A18)
    } else {
        0
    }
}

/// Whether an SMC key matches a table key with `%` wildcards.
pub fn key_matches(pattern: &str, key: &str) -> bool {
    pattern.len() == key.len()
        && pattern
            .bytes()
            .zip(key.bytes())
            .all(|(p, k)| p == b'%' || p == k)
}

/// The readable name of `key` in a table entry (`%` in the name becomes the
/// wildcard character of the key, as Stats does).
pub fn name_for(entry: &S, key: &str) -> String {
    if !entry.name.contains('%') {
        return entry.name.to_string();
    }
    let wild: String = entry
        .key
        .bytes()
        .zip(key.bytes())
        .filter(|(p, _)| *p == b'%')
        .map(|(_, k)| k as char)
        .collect();
    entry.name.replace('%', &wild)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn families_from_brand() {
        assert_eq!(family("Apple M5"), M5);
        assert_eq!(family("Apple M4 Pro"), M4_PRO);
        assert_eq!(family("Apple M4"), M4_BASE);
        assert_eq!(family("Apple M1 Max"), M1);
        assert_eq!(family("Intel(R) Core(TM) i7-9750H CPU @ 2.60GHz"), INTEL);
        assert_eq!(family("AMD Ryzen"), 0);
    }

    #[test]
    fn wildcard_keys_and_names() {
        assert!(key_matches("TC%C", "TC3C"));
        assert!(!key_matches("TC%C", "TC3c"));
        let e = SENSORS.iter().find(|s| s.key == "TC%C").unwrap();
        assert_eq!(name_for(e, "TC3C"), "CPU Core 3");
        assert!(
            SENSORS
                .iter()
                .filter(|s| s.on & M5 != 0 && s.group == "CPU")
                .count()
                >= 18
        );
    }

    #[test]
    fn kinds_and_averages_are_documented() {
        for s in SENSORS {
            assert!(
                ["temperature", "voltage", "current", "power"].contains(&s.kind),
                "{}",
                s.key
            );
            assert!(!s.average || ["CPU", "GPU"].contains(&s.group), "{}", s.key);
        }
    }
}

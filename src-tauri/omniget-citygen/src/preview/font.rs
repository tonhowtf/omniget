fn fold(c: char) -> char {
    match c {
        'á' | 'à' | 'â' | 'ã' => 'a',
        'Á' | 'À' | 'Â' | 'Ã' => 'A',
        'é' | 'ê' => 'e',
        'É' | 'Ê' => 'E',
        'í' => 'i',
        'Í' => 'I',
        'ó' | 'ô' | 'õ' => 'o',
        'Ó' | 'Ô' | 'Õ' => 'O',
        'ú' => 'u',
        'Ú' => 'U',
        'ç' => 'c',
        'Ç' => 'C',
        c => c,
    }
}

/// 7 rows of 5 bits (bit 4 = leftmost column).
pub fn glyph(c: char) -> [u8; 7] {
    let c = fold(c);
    let rows = GLYPHS
        .iter()
        .find(|g| g.0 == c)
        .map(|g| g.1)
        .unwrap_or(GLYPHS.iter().find(|g| g.0 == '?').unwrap().1);
    let mut out = [0u8; 7];
    for (i, r) in rows.iter().enumerate() {
        for (j, ch) in r.chars().enumerate() {
            if ch == '#' {
                out[i] |= 1 << (4 - j);
            }
        }
    }
    out
}

/// Width in pixels of `text` at `scale` (6 px per glyph incl. spacing).
pub fn width(text: &str, scale: i32) -> i32 {
    text.chars().count() as i32 * 6 * scale - scale
}

/// Draw `text` with its top-left corner at (x, y).
pub fn draw(img: &mut super::Image, text: &str, x: i32, y: i32, scale: i32, rgb: [u8; 3]) {
    let mut cx = x;
    for ch in text.chars() {
        let g = glyph(ch);
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits & (1 << (4 - col)) != 0 {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            img.put(cx + col * scale + sx, y + row as i32 * scale + sy, rgb);
                        }
                    }
                }
            }
        }
        cx += 6 * scale;
    }
}
